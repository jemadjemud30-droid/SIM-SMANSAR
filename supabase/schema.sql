-- Jalankan skrip ini di Supabase Dashboard -> SQL Editor -> New Query
-- Skrip ini membuat tabel pengaturan sekolah, kredensial admin privat, dan tabel link aplikasi

create table if not exists public.school_settings (
  id integer primary key default 1,
  logo_url text not null default '',
  title_1 text not null default 'SMA Negeri 1 Nusantara',
  title_2 text not null default 'Portal Aplikasi & Tautan Web Sekolah',
  title_3 text not null default 'Akses Cepat Layanan Akademik, Administrasi & Pembelajaran',
  updated_at timestamptz not null default now()
);

insert into public.school_settings (id)
values (1)
on conflict (id) do nothing;

-- Tabel kredensial privat (hanya diakses dari server menggunakan SUPABASE_SERVICE_ROLE_KEY)
create table if not exists public.admin_credentials (
  id integer primary key default 1,
  password_hash text,
  teacher_password_hash text,
  updated_at timestamptz not null default now()
);

alter table public.admin_credentials
  add column if not exists teacher_password_hash text;

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

insert into public.categories (name, sort_order)
values
  ('Akademik', 1),
  ('Pembelajaran', 2),
  ('Administrasi', 3),
  ('Alat', 4),
  ('Referensi', 5),
  ('Umum', 6)
on conflict (name) do nothing;

create table if not exists public.links (
  id bigint generated by default as identity primary key,
  title text not null,
  url text not null,
  description text not null default '',
  category text not null default 'Akademik',
  icon_name text not null default 'Globe',
  icon_color text not null default 'blue',
  icon_style text not null default '3d',
  for_students boolean not null default true,
  for_teachers boolean not null default true,
  is_published boolean not null default true,
  is_pinned boolean not null default false,
  click_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.links
  add column if not exists icon_style text not null default '3d',
  add column if not exists for_students boolean not null default true,
  add column if not exists for_teachers boolean not null default true;

-- Aktifkan Row Level Security (RLS)
alter table public.school_settings enable row level security;
alter table public.admin_credentials enable row level security;
alter table public.categories enable row level security;
alter table public.links enable row level security;

-- Pengaturan sekolah dapat dibaca publik (halaman portal depan)
drop policy if exists "Public can read school settings" on public.school_settings;
create policy "Public can read school settings"
  on public.school_settings for select
  to anon, authenticated
  using (true);

-- Kategori dapat dibaca publik (filter portal pengguna)
drop policy if exists "Public can read categories" on public.categories;
create policy "Public can read categories"
  on public.categories for select
  to anon, authenticated
  using (true);

-- Link yang sudah dipublish untuk siswa dapat dibaca publik tanpa password
drop policy if exists "Public can read published links" on public.links;
create policy "Public can read published links"
  on public.links for select
  to anon, authenticated
  using (is_published = true and for_students = true);

-- Catatan: Tabel admin_credentials dan link khusus guru hanya diakses
-- melalui backend Express menggunakan SUPABASE_SERVICE_ROLE_KEY.
